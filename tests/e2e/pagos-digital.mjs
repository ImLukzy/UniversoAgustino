import process from "node:process";
import { api, browserFor, check, login, withDatabase } from "./helper.mjs";
import { cleanupOrder, createOrder, proofFile, waitOrder } from "./paymentHelpers.mjs";

await withDatabase(async (db) => {
  const started = new Date(), buyer = await db.user.findUniqueOrThrow({ where: { email: "qa-est@unsa.edu.pe" } });
  const seller = await db.user.findUniqueOrThrow({ where: { email: "qa-vendedor@unsa.edu.pe" } });
  const moderator = await db.user.findUniqueOrThrow({ where: { email: "qa-mod@unsa.edu.pe" } });
  const doc = await db.document.findUniqueOrThrow({ where: { id: "qa-e2e-pay-accepted" } });
  let orderId;
  const buyerSession = await browserFor("est"), modSession = await browserFor("mod"), sellerSession = await browserFor("vendedor");
  try {
    const order = await createOrder(doc.id); orderId = order.id;
    check(order.amountCents === 1500 && order.feeCents === 195 && order.netCents === 1305, "snapshot precio, comisión 13% y neto");
    await buyerSession.page.goto(`${process.env.E2E_WEB_URL}/checkout/${order.id}`);
    await buyerSession.page.getByLabel("Cuenta destino del equipo").waitFor();
    const account = await db.paymentAccount.findFirstOrThrow({ where: { userId: moderator.id, holder: "QA Cuenta", number: "900000000", active: true } });
    await buyerSession.page.getByLabel("Cuenta destino del equipo").selectOption(account.id);
    check(await buyerSession.page.getByLabel("Cuenta destino del equipo").inputValue() === account.id, "elige la cuenta ficticia QA");
    await buyerSession.page.getByText("900000000").waitFor();
    check(await buyerSession.page.getByRole("button", { name: "Ya pagué" }).isDisabled(), "sin foto no permite enviar pago");
    const missingPhoto = await api(`/orders/${order.id}/pay`, { token: await login("est"), method: "POST", body: { paymentAccountId: account.id } });
    check(missingPhoto.status === 400, "API rechaza pago sin foto");
    const submitProof = async () => {
      await buyerSession.page.locator('input[type="file"]').setInputFiles(proofFile);
      await buyerSession.page.getByText("payment-proof.png").waitFor();
      await buyerSession.page.getByRole("button", { name: "Ya pagué" }).click();
      await waitOrder(db, order.id, (row) => row.status === "PAID" && !!row.payProofUrl && row.paymentRejectedReason === null);
    };
    await submitProof();
    const sent = await db.notification.findMany({ where: { createdAt: { gte: started }, type: "ORDER_PAID", body: { contains: doc.title } } });
    check([buyer.id, seller.id, moderator.id].every((id) => sent.some((notice) => notice.userId === id)), "aviso de pago a comprador, vendedor y cobrador");
    await modSession.page.goto(`${process.env.E2E_WEB_URL}/panel/pagos-por-verificar`);
    const card = modSession.page.locator("article.card").filter({ hasText: doc.title });
    await card.getByText("Estudiante QA").waitFor(); await card.getByText("QA Cuenta").waitFor();
    await card.getByText("900000000").waitFor();
    await card.getByText("S/ 15").waitFor(); await card.getByRole("img", { name: "Comprobante del comprador" }).waitFor();
    const rejection = "QA E2E: imagen inicial ilegible.";
    await card.getByLabel(/Motivo para denegar/).fill(rejection);
    await card.getByRole("button", { name: "Denegar comprobante" }).click();
    await waitOrder(db, order.id, (row) => row.status === "PAID" && row.paymentRejectedReason === rejection);
    const rejectedNotices = await db.notification.findMany({ where: { createdAt: { gte: started }, type: "PAYMENT_REJECTED", body: { contains: doc.title } } });
    check([buyer.id, seller.id].every((id) => rejectedNotices.some((notice) => notice.userId === id)), "aviso de denegación a comprador y vendedor");
    await buyerSession.page.reload();
    await buyerSession.page.getByRole("alert").filter({ hasText: rejection }).waitFor();
    await submitProof();
    await modSession.page.reload();
    const review = modSession.page.locator("article.card").filter({ hasText: doc.title });
    modSession.page.on("dialog", (dialog) => void dialog.accept());
    await review.getByRole("button", { name: "Aceptar pago" }).click();
    const payout = await waitOrder(db, order.id, (row) => row.status === "ESCROW").then(() => db.payout.findUniqueOrThrow({ where: { orderId: order.id } }));
    check(payout.status === "PENDING" && payout.feeCents === 195 && payout.netCents === 1305, "aceptar crea liquidación pendiente por el neto del 13%");
    check(await db.documentAccessGrant.count({ where: { orderId: order.id, revokedAt: null } }) === 1, "aceptar concede acceso permanente");
    const verified = await db.notification.findMany({ where: { createdAt: { gte: started }, type: "PAYMENT_VERIFIED", body: { contains: doc.title } } });
    check([buyer.id, seller.id].every((id) => verified.some((notice) => notice.userId === id)), "aviso de pago verificado a comprador y vendedor");
    check(await db.notification.count({ where: { userId: seller.id, type: "PAYOUT_PENDING", body: { contains: doc.title }, createdAt: { gte: started } } }) > 0, "aviso de liquidación pendiente al vendedor");
    await buyerSession.page.goto(`${process.env.E2E_WEB_URL}/pedidos`);
    const buyerOrder = buyerSession.page.locator("article.card").filter({ hasText: doc.title });
    await buyerOrder.getByRole("button", { name: "Descargar" }).click();
    check((await api(`/documents/${doc.id}/download`, { token: await login("est") })).status === 200, "comprador abre y descarga el apunte verificado");
    await modSession.page.goto(`${process.env.E2E_WEB_URL}/panel/pagos-a-vendedores`);
    const payoutCard = modSession.page.locator("article.card").filter({ hasText: doc.title });
    await payoutCard.getByText("S/ 13.05").waitFor();
    await payoutCard.locator('input[type="file"]').setInputFiles(proofFile);
    await payoutCard.getByText("Foto adjunta").waitFor();
    await payoutCard.getByRole("button", { name: "Registrar liquidación" }).click();
    await waitOrder(db, order.id, (row) => row.status === "RELEASED");
    check((await db.payout.findUniqueOrThrow({ where: { id: payout.id } })).status === "COMPLETED", "liquidación completada");
    await modSession.page.goto(`${process.env.E2E_WEB_URL}/panel/completas`);
    await modSession.page.locator("article.card").filter({ hasText: doc.title }).getByText("Pagado").waitFor();
    await sellerSession.page.goto(`${process.env.E2E_WEB_URL}/ventas`);
    const sellerPayout = sellerSession.page.locator("article.card").filter({ hasText: doc.title });
    await sellerPayout.getByText("Precio", { exact: true }).waitFor();
    await sellerPayout.getByText("Comisión 13%", { exact: true }).waitFor();
    await sellerPayout.getByText("Neto recibido").waitFor(); await sellerPayout.getByText("Pagado", { exact: true }).waitFor();
    await sellerPayout.getByRole("img", { name: "Comprobante del pago recibido" }).waitFor();
    check(await db.notification.count({ where: { userId: seller.id, type: "PAYOUT_COMPLETED", createdAt: { gte: started } } }) > 0, "aviso de liquidación pagada al vendedor");
    check(await db.notification.count({ where: { userId: buyer.id, type: "ORDER_RELEASED", createdAt: { gte: started } } }) > 0, "aviso de liquidación completada al comprador");
    globalThis.console.log("✓ pagos digitales: denegación y reenvío, verificación, acceso, liquidación, Mis cobros y notificaciones");
  } finally {
    await Promise.all([buyerSession.browser.close(), modSession.browser.close(), sellerSession.browser.close()]);
    if (orderId) await cleanupOrder(db, orderId);
  }
});
